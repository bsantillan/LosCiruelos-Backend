-- =====================================================================
-- V12: registro de los códigos de verificación mandados por WhatsApp.
-- Cada mensaje cuesta: se limitan por usuario y por número (por defecto 5 cada 24 h y uno por minuto).
-- =====================================================================

CREATE TABLE public.envios_codigo_telefono (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  bigint NOT NULL REFERENCES public.usuarios (id),
    telefono    varchar(20) NOT NULL,
    enviado_at  timestamp(6) NOT NULL
);

CREATE INDEX idx_envios_codigo_usuario ON public.envios_codigo_telefono (usuario_id, enviado_at);
CREATE INDEX idx_envios_codigo_telefono ON public.envios_codigo_telefono (telefono, enviado_at);
