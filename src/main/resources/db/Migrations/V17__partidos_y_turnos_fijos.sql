-- =====================================================================
-- V17: partidos de 4 jugadores y turnos fijos (los arma el ADMIN).
-- Un partido es una reserva tipo PARTIDO con sus 4 jugadores (clientes registrados o
-- invitados). No vence: sin nada pagado queda CONFIRMADA y cada jugador paga su parte en el
-- club. Un turno fijo repite el mismo partido todas las semanas.
-- =====================================================================

ALTER TABLE public.reservas DROP CONSTRAINT ck_reservas_estado;
ALTER TABLE public.reservas ADD CONSTRAINT ck_reservas_estado CHECK (estado IN
    ('PENDIENTE', 'CONFIRMADA', 'SEÑADA', 'PARCIALMENTE_PAGADA', 'PAGADA', 'CANCELADA', 'EXPIRADA', 'COMPLETADA'));

ALTER TABLE public.reservas ADD COLUMN tipo varchar(20) NOT NULL DEFAULT 'NORMAL'
    CONSTRAINT ck_reservas_tipo CHECK (tipo IN ('NORMAL', 'PARTIDO'));

-- ---------------------------------------------------------------------
-- Turnos fijos
-- ---------------------------------------------------------------------

CREATE TABLE public.turnos_fijos (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cancha_id        bigint NOT NULL REFERENCES public.canchas (id),
    dia_semana       varchar(10) NOT NULL,
    hora_inicio      time(0) NOT NULL,
    hora_fin         time(0) NOT NULL,
    desde            date NOT NULL,                                   -- primera fecha que se juega
    cantidad_pelotas integer NOT NULL DEFAULT 0,
    cantidad_paletas integer NOT NULL DEFAULT 0,
    activo           boolean NOT NULL DEFAULT true,
    created_by_id    bigint NOT NULL REFERENCES public.usuarios (id),
    created_at       timestamp(6) NOT NULL,
    dado_de_baja_at  timestamp(6),
    CONSTRAINT ck_turnos_fijos_dia CHECK (dia_semana IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    CONSTRAINT ck_turnos_fijos_horario CHECK (hora_inicio < hora_fin),
    CONSTRAINT ck_turnos_fijos_productos CHECK (cantidad_pelotas >= 0 AND cantidad_paletas >= 0)
);

-- dos turnos fijos activos de la misma cancha y el mismo día no se superponen
CREATE INDEX idx_turnos_fijos_activos ON public.turnos_fijos (cancha_id, dia_semana) WHERE activo;

CREATE TABLE public.turno_fijo_jugadores (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno_fijo_id bigint NOT NULL REFERENCES public.turnos_fijos (id) ON DELETE CASCADE,
    posicion      integer NOT NULL,
    usuario_id    bigint REFERENCES public.usuarios (id),            -- null: invitado
    nombre        varchar(100),                                      -- invitado
    telefono      varchar(20),                                       -- invitado (opcional)
    CONSTRAINT ck_turno_fijo_jugadores_posicion CHECK (posicion BETWEEN 1 AND 4),
    CONSTRAINT ck_turno_fijo_jugadores_quien CHECK (usuario_id IS NOT NULL OR nombre IS NOT NULL),
    -- diferidas: al reordenar jugadores, dos filas intercambian valores en el mismo flush
    CONSTRAINT uk_turno_fijo_jugadores_posicion UNIQUE (turno_fijo_id, posicion) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT uk_turno_fijo_jugadores_usuario UNIQUE (turno_fijo_id, usuario_id) DEFERRABLE INITIALLY DEFERRED
);

-- ---------------------------------------------------------------------
-- Partidos: reservas creadas por un turno fijo y jugadores
-- ---------------------------------------------------------------------

ALTER TABLE public.reservas ADD COLUMN turno_fijo_id bigint REFERENCES public.turnos_fijos (id);

-- un partido por turno fijo y fecha: si se dio de baja esa fecha, la reserva CANCELADA queda y
-- el job no la vuelve a crear
CREATE UNIQUE INDEX uk_reservas_turno_fijo_fecha ON public.reservas (turno_fijo_id, fecha_reserva)
    WHERE turno_fijo_id IS NOT NULL;

CREATE TABLE public.reserva_jugadores (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id bigint NOT NULL REFERENCES public.reservas (id) ON DELETE CASCADE,
    posicion   integer NOT NULL,
    usuario_id bigint REFERENCES public.usuarios (id),               -- null: invitado
    nombre     varchar(100),                                         -- invitado
    telefono   varchar(20),                                          -- invitado (opcional)
    CONSTRAINT ck_reserva_jugadores_posicion CHECK (posicion BETWEEN 1 AND 4),
    CONSTRAINT ck_reserva_jugadores_quien CHECK (usuario_id IS NOT NULL OR nombre IS NOT NULL),
    CONSTRAINT uk_reserva_jugadores_posicion UNIQUE (reserva_id, posicion) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT uk_reserva_jugadores_usuario UNIQUE (reserva_id, usuario_id) DEFERRABLE INITIALLY DEFERRED
);

-- "Mis reservas" de un jugador registrado
CREATE INDEX idx_reserva_jugadores_usuario ON public.reserva_jugadores (usuario_id) WHERE usuario_id IS NOT NULL;

-- Qué jugador pagó (o a quién se le bonificó) en un partido
ALTER TABLE public.pagos ADD COLUMN jugador_id bigint REFERENCES public.reserva_jugadores (id);
CREATE INDEX idx_pagos_jugador ON public.pagos (jugador_id) WHERE jugador_id IS NOT NULL;
