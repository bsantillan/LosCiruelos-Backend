-- =====================================================================
-- V31: devoluciones de ventas sueltas (solo ADMIN). El cliente devuelve todo o parte de lo que
-- compró: queda una devolución con fecha, quién la registró, motivo y monto, que cuenta en la caja
-- del día en que se devuelve (los días anteriores no cambian). Cada ítem dice si el producto vuelve
-- al stock. venta_items.devueltas lleva cuántas unidades de cada ítem ya se devolvieron.
-- =====================================================================

ALTER TABLE public.venta_items ADD COLUMN devueltas integer NOT NULL DEFAULT 0;
ALTER TABLE public.venta_items ADD CONSTRAINT ck_venta_items_devueltas CHECK (devueltas BETWEEN 0 AND cantidad);

CREATE TABLE public.venta_devoluciones (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id          bigint NOT NULL REFERENCES public.ventas (id) ON DELETE CASCADE,
    created_at        timestamp(6) NOT NULL,
    registrada_por_id bigint NOT NULL REFERENCES public.usuarios (id),
    motivo            varchar(200) NOT NULL,
    monto             numeric(10,2) NOT NULL,
    CONSTRAINT ck_venta_devoluciones_monto CHECK (monto > 0)
);
CREATE INDEX idx_venta_devoluciones_venta ON public.venta_devoluciones (venta_id);
-- la caja suma las devoluciones del período
CREATE INDEX idx_venta_devoluciones_created_at ON public.venta_devoluciones (created_at);

CREATE TABLE public.venta_devolucion_items (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    devolucion_id   bigint NOT NULL REFERENCES public.venta_devoluciones (id) ON DELETE CASCADE,
    venta_item_id   bigint NOT NULL REFERENCES public.venta_items (id) ON DELETE CASCADE,
    cantidad        integer NOT NULL,
    vuelve_al_stock boolean NOT NULL,
    CONSTRAINT ck_venta_devolucion_items_cantidad CHECK (cantidad > 0),
    CONSTRAINT uk_venta_devolucion_items UNIQUE (devolucion_id, venta_item_id)
);
