-- =====================================================================
-- V26: un turno fijo pide cualquier producto del catálogo (no solo pelotas y paletas): sus
-- productos pasan a turno_fijo_productos y se van cantidad_pelotas y cantidad_paletas.
-- =====================================================================

CREATE TABLE public.turno_fijo_productos (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno_fijo_id bigint NOT NULL REFERENCES public.turnos_fijos (id) ON DELETE CASCADE,
    producto_id   bigint NOT NULL REFERENCES public.productos (id),
    cantidad      integer NOT NULL,
    CONSTRAINT ck_turno_fijo_productos_cantidad CHECK (cantidad > 0),
    CONSTRAINT uk_turno_fijo_productos UNIQUE (turno_fijo_id, producto_id)
);

INSERT INTO public.turno_fijo_productos (turno_fijo_id, producto_id, cantidad)
SELECT tf.id, p.id, tf.cantidad_pelotas
FROM public.turnos_fijos tf JOIN public.productos p ON p.codigo = 'PELOTAS'
WHERE tf.cantidad_pelotas > 0;

INSERT INTO public.turno_fijo_productos (turno_fijo_id, producto_id, cantidad)
SELECT tf.id, p.id, tf.cantidad_paletas
FROM public.turnos_fijos tf JOIN public.productos p ON p.codigo = 'PALETAS'
WHERE tf.cantidad_paletas > 0;

ALTER TABLE public.turnos_fijos
    DROP CONSTRAINT ck_turnos_fijos_productos,
    DROP COLUMN cantidad_pelotas,
    DROP COLUMN cantidad_paletas;
