-- V1: esquema inicial de Los Ciruelos.
--
-- Unifica las migraciones de desarrollo (V1 a V48 y las migraciones Java V13 y V39) antes de la
-- primera salida a producción: es el esquema que quedaba al aplicarlas sobre una base vacía (sacado
-- con pg_dump --schema-only). Las migraciones que solo corregían datos viejos no hacen falta en una
-- base nueva. La historia de cada cambio queda en git y en docs/base-de-datos.md.
--
-- Lo que no está acá lo crea la app al arrancar (DataInitializer): el ADMIN inicial, la configuración
-- del club y las 4 canchas.
--
-- Desde acá, cada cambio de esquema es una migración nueva (V2, V3, …): esta no se vuelve a editar.
-- =====================================================================

