-- =====================================================================
-- V27: ventas sueltas. El personal vende productos sin reserva, partido ni turno (una bebida,
-- un tubo de pelotas); se cobran en el momento, en efectivo o con Mercado Pago en el club, y
-- entran en la caja del día. Opcionalmente se asocian a un cliente.
-- =====================================================================

CREATE TABLE public.ventas (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        timestamp(6) NOT NULL,
    total             numeric(10,2) NOT NULL,
    medio             varchar(20) NOT NULL,
    cliente_id        bigint REFERENCES public.usuarios (id),            -- opcional
    registrado_por_id bigint NOT NULL REFERENCES public.usuarios (id),
    CONSTRAINT ck_ventas_medio CHECK (medio IN ('EFECTIVO', 'MERCADO_PAGO')),
    CONSTRAINT ck_ventas_total CHECK (total >= 0)
);
CREATE INDEX idx_ventas_created_at ON public.ventas (created_at);

CREATE TABLE public.venta_items (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id        bigint NOT NULL REFERENCES public.ventas (id) ON DELETE CASCADE,
    producto_id     bigint NOT NULL REFERENCES public.productos (id),
    cantidad        integer NOT NULL,
    precio_unitario numeric(10,2) NOT NULL,
    CONSTRAINT ck_venta_items_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_venta_items_precio CHECK (precio_unitario >= 0),
    CONSTRAINT uk_venta_items UNIQUE (venta_id, producto_id)
);
