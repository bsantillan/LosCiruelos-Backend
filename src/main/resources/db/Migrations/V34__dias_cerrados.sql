-- =====================================================================
-- V34: días puntuales en que el club no abre (un feriado, una obra), además del horario semanal.
-- Ese día no se puede reservar y los turnos fijos no crean su partido. Al cerrar un día, las
-- reservas de ese día que todavía no empezaron se cancelan con reembolso total (si el ADMIN confirma).
-- =====================================================================

CREATE TABLE public.dias_cerrados (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    configuracion_id bigint NOT NULL REFERENCES public.configuracion (id),
    fecha            date NOT NULL,
    motivo           varchar(200) NOT NULL,
    created_at       timestamp(6) NOT NULL,
    created_by_id    bigint NOT NULL REFERENCES public.usuarios (id),
    CONSTRAINT uk_dias_cerrados_fecha UNIQUE (fecha)
);
