-- ---------------------------------------------------------------------
-- Reservas y pagos
-- ---------------------------------------------------------------------

CREATE TABLE public.reservas (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cancha_id      bigint NOT NULL REFERENCES public.canchas (id),
    cliente_id     bigint NOT NULL REFERENCES public.usuarios (id),   -- para quién es
    created_by_id  bigint NOT NULL REFERENCES public.usuarios (id),   -- quién la cargó
    fecha_reserva  date NOT NULL,
    hora_inicio    time(0) NOT NULL,
    hora_fin       time(0) NOT NULL,
    monto_total    numeric(10,2) NOT NULL,                            -- cancha + productos
    estado         varchar(255) NOT NULL,
    created_at     timestamp(6) NOT NULL,
    expires_at     timestamp(6),                                      -- plazo para pagar
    CONSTRAINT ck_reservas_estado CHECK (estado IN
        ('PENDIENTE', 'SEÑADA', 'PARCIALMENTE_PAGADA', 'PAGADA', 'CANCELADA', 'EXPIRADA', 'COMPLETADA')),
    CONSTRAINT ck_reservas_horario CHECK (hora_inicio < hora_fin),
    -- dos reservas activas de la misma cancha no se pueden superponer
    CONSTRAINT reservas_sin_solapamiento EXCLUDE USING gist (
        cancha_id WITH =,
        tsrange(fecha_reserva + hora_inicio, fecha_reserva + hora_fin) WITH &&
    ) WHERE (estado NOT IN ('CANCELADA', 'EXPIRADA'))
);

CREATE INDEX idx_reservas_estado_expires ON public.reservas (estado, expires_at);
CREATE INDEX idx_reservas_cancha_fecha ON public.reservas (cancha_id, fecha_reserva);
CREATE INDEX idx_reservas_cliente ON public.reservas (cliente_id);
CREATE INDEX idx_reservas_fecha ON public.reservas (fecha_reserva);

-- Productos pedidos en cada reserva, con el precio del momento
CREATE TABLE public.reserva_productos (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id        bigint NOT NULL REFERENCES public.reservas (id),
    producto_id       bigint NOT NULL REFERENCES public.productos (id),
    cantidad          integer NOT NULL,
    precio_unitario   numeric(10,2) NOT NULL,
    cantidad_devuelta integer,                           -- alquileres: null hasta registrar la devolución
    devuelta_at       timestamp(6),
    CONSTRAINT uk_reserva_productos UNIQUE (reserva_id, producto_id),
    CONSTRAINT ck_reserva_productos_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_reserva_productos_precio CHECK (precio_unitario >= 0),
    CONSTRAINT ck_reserva_productos_devuelta CHECK (cantidad_devuelta BETWEEN 0 AND cantidad)
);

CREATE INDEX idx_reserva_productos_producto ON public.reserva_productos (producto_id);

CREATE TABLE public.pagos (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id          bigint NOT NULL REFERENCES public.reservas (id),
    monto               numeric(10,2) NOT NULL,
    estado              varchar(255) NOT NULL,
    provider            varchar(255) NOT NULL,
    created_at          timestamp(6) NOT NULL,
    paid_at             timestamp(6),
    external_payment_id varchar(255),                     -- id del pago en Mercado Pago
    preference_id       varchar(255),                     -- id de la preferencia de Mercado Pago
    CONSTRAINT ck_pagos_estado CHECK (estado IN
        ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'EN_PROCESO', 'DEVUELTO', 'EXPIRADO', 'A_REEMBOLSAR')),
    CONSTRAINT ck_pagos_provider CHECK (provider IN ('MERCADO_PAGO', 'MANUAL'))
);

CREATE INDEX idx_pagos_reserva ON public.pagos (reserva_id);
CREATE UNIQUE INDEX uk_pagos_external_payment_id ON public.pagos (external_payment_id)
    WHERE external_payment_id IS NOT NULL;
