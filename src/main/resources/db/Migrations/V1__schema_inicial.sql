-- Necesaria para la restricción de solapamiento de reservas (EXCLUDE con = sobre bigint)
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------------------------------------------------------------------
-- Usuarios y autenticación
-- ---------------------------------------------------------------------

CREATE TABLE public.usuarios (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            varchar(50),
    apellido          varchar(50),
    email             varchar(100) NOT NULL,
    telefono          varchar(20),
    password_hash     varchar(255),                       -- null en cuentas de Google
    terms_accepted    boolean NOT NULL,
    terms_accepted_at timestamp(6) NOT NULL,              -- también es la fecha de alta
    email_verificado  boolean NOT NULL,
    enabled           boolean NOT NULL,                   -- false = cuenta desactivada
    rol               varchar(20) NOT NULL,
    provider          varchar(20) NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('CLIENTE', 'EMPLEADO', 'ADMIN', 'PROFESOR')),
    CONSTRAINT ck_usuarios_provider CHECK (provider IN ('LOCAL', 'GOOGLE'))
);

-- Perfil de jugador (solo clientes)
CREATE TABLE public.clientes (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id               bigint NOT NULL REFERENCES public.usuarios (id),
    categoria                varchar(20),
    posicion                 varchar(10),
    categoria_actualizada_at timestamp(6),                -- inicio del plazo de 24 h para cambiarla
    categoria_modificada     boolean NOT NULL DEFAULT false,
    CONSTRAINT uk_clientes_usuario UNIQUE (usuario_id),
    CONSTRAINT ck_clientes_categoria CHECK (categoria IN
        ('Primera', 'Segunda', 'Tercera', 'Cuarta', 'Quinta', 'Sexta', 'Septima', 'Principiante')),
    CONSTRAINT ck_clientes_posicion CHECK (posicion IN ('Drive', 'Reves', 'Ambos'))
);

CREATE TABLE public.refresh_tokens (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token            varchar(255) NOT NULL,
    fecha_expiracion timestamp(6) with time zone NOT NULL,
    usuario_id       bigint REFERENCES public.usuarios (id),
    CONSTRAINT uk_refresh_tokens_token UNIQUE (token),
    CONSTRAINT uk_refresh_tokens_usuario UNIQUE (usuario_id)   -- una sesión por usuario
);

-- Códigos de 6 dígitos (verificación de email y reset de contraseña)
CREATE TABLE public.verification_tokens (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       bigint REFERENCES public.usuarios (id),
    token            varchar(6) NOT NULL,
    fecha_expiracion timestamp(6) with time zone NOT NULL,
    type             varchar(20) NOT NULL,
    verificado       boolean NOT NULL DEFAULT false,
    intentos         integer NOT NULL DEFAULT 0,
    CONSTRAINT uk_verification_tokens_usuario_type UNIQUE (usuario_id, type),
    CONSTRAINT ck_verification_tokens_type CHECK (type IN ('VERIFY_EMAIL', 'PASSWORD_RESET'))
);

-- ---------------------------------------------------------------------
-- Configuración del club
-- ---------------------------------------------------------------------

CREATE TABLE public.configuracion (
    id                    bigint PRIMARY KEY,                  -- registro único, id = 1
    monto_reserva         numeric(10,2) NOT NULL,
    monto_x_media_hora    numeric(10,2) NOT NULL,
    porcentaje_senia      numeric(5,2) NOT NULL,
    duracion_minima_turno integer NOT NULL,
    duracion_maxima_turno integer NOT NULL
);

CREATE TABLE public.dias (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia                      varchar(10) NOT NULL,             -- 'Lunes' ... 'Domingo'
    horario_inicio           time(0) NOT NULL,
    horario_fin              time(0) NOT NULL,
    configuracion_general_id bigint NOT NULL REFERENCES public.configuracion (id)
);

CREATE TABLE public.canchas (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero      integer NOT NULL,
    descripcion varchar(300) NOT NULL
);

-- Stock de productos (pelotas, paletas y otros)
CREATE TABLE public.productos (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      varchar(30),                                   -- PELOTAS / PALETAS; null en el resto
    nombre      varchar(100) NOT NULL,
    descripcion varchar(300),
    tipo        varchar(20) NOT NULL,
    precio      numeric(10,2) NOT NULL,                        -- por unidad
    stock       integer NOT NULL,                              -- VENTA: disponibles · ALQUILER: total
    activo      boolean NOT NULL DEFAULT true,
    CONSTRAINT uk_productos_codigo UNIQUE (codigo),
    CONSTRAINT ck_productos_tipo CHECK (tipo IN ('VENTA', 'ALQUILER')),
    CONSTRAINT ck_productos_precio CHECK (precio >= 0),
    CONSTRAINT ck_productos_stock CHECK (stock >= 0)
);

CREATE UNIQUE INDEX uk_productos_nombre ON public.productos (lower(nombre));

